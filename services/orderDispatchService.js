const { Logger } = require('../utils');
const { assertStageOpen } = require('../utils/staleWriteGuard');

// v2 normalized schema (order-to-dispatch-db-v2). The ENTIRE file now runs
// against this — the legacy order_dispatch surfaces (getAllOrders, update,
// delete, suffixes) were the last old-RDS holdouts and are migrated below.
const { dbV2, schema } = require('../config/db-v2.ts');
const { eq, and, or, isNull, isNotNull, sql, asc, desc, inArray, notInArray } = require('drizzle-orm');
const { alias } = require('drizzle-orm/pg-core');
const { getPlannedAt, isStockTransfer } = require('./stageUtils');

// Order-header columns that updateOrder is allowed to change (drizzle prop
// names). Per-line fields (sku, qty, rates) live on order_items and are managed
// by the stage services, never here. Input keys may arrive snake_case (old API)
// or camelCase — both are normalized to these.
const UPDATABLE_ORDER_FIELDS = new Set([
  'customerId', 'depotId', 'brokerId', 'salespersonId',
  // orderCategory (Sales vs Stock Transfer) is DELIBERATELY NOT editable after punch:
  // it drives both workflow routing AND the qty hard-cap (Sales enforced, ST exempt).
  // Flipping it post-punch would leak the ST exemption into a Sales order (or vice
  // versa) - e.g. an ST over-approved above its punch, then flipped to Sales, could
  // dispatch past its punch. A mis-punched category is fixed by delete + re-punch.
  'orderType', 'deliveryPurpose', 'orderThrough',
  'customerType', 'partySoDate', 'startDate', 'endDate', 'deliveryDate', 'futurePeriodDate',
  'customerContactPersonName', 'customerContactPersonWhatsappNo',
  'customerAddress', 'customerDeliveryAddress',
  'paymentTerms', 'advancePaymentToBeTaken', 'advanceAmount',
  'typeOfTransporting', 'freightRate',
  'billCompanyName', 'billAddress', 'shipCompanyName', 'shipAddress',
  'gst', 'manualSaudaNo', 'uploadSo', 'uploadCopy', 'orderPunchRemarks',
]);

const toCamelCase = (key) => key.replace(/_([a-z])/g, (_, c) => c.toUpperCase());

const FY_CUTOVER = new Date('2026-04-01T00:00:00.000Z');

function getFinancialYearDetails(date) {
  const d = date ? new Date(date) : new Date();
  const isLegacy = d < FY_CUTOVER;
  const month = d.getUTCMonth();
  const year = d.getUTCFullYear();
  const fyStart = month >= 3 ? year : year - 1;
  const fy = `${String(fyStart).slice(-2)}-${String(fyStart + 1).slice(-2)}`;
  return { fy, isLegacy };
}

// Per-FY sequential order number: DO/26-27/0084 (or legacy DO-084 pre-cutover).
// Scans MAX(order_no) for the current prefix, +1. In v2 there is one orders row
// per real order, so NO letter-suffix variants are needed anymore.
async function generateOrderNo(tx, date) {
  const { fy, isLegacy } = getFinancialYearDetails(date);
  const prefix = isLegacy ? 'DO-' : `DO/${fy}/`;
  const padding = isLegacy ? 3 : 4;
  const result = await tx.execute(
    sql`SELECT order_no FROM orders WHERE order_no LIKE ${prefix + '%'} ORDER BY order_no DESC LIMIT 1`
  );
  let nextNum = 1;
  if (result.rows.length > 0) {
    const parsed = parseInt(result.rows[0].order_no.replace(prefix, ''), 10);
    if (!isNaN(parsed)) nextNum = parsed + 1;
  }
  return `${prefix}${String(nextNum).padStart(padding, '0')}`;
}

class OrderDispatchService {
  /**
   * Create order(s) - handles single or multiple products
   * Order number is now auto-generated by database trigger
   * @param {Object} orderData - Order data from form
   * @param {Array} products - Array of products (if multiple)
   * @returns {Promise<Object>} Created orders with generated order_no
   */
  /**
   * Order Punch (gate 0): create one `orders` row + N `order_items` rows in one
   * transaction, generate the order_no, and seed the first gate per item
   * (pre_approvals for pre-approval orders, order_approvals for regular ones -
   * regular orders skip Pre-Approval entirely, mirroring the old planned_1 vs
   * planned_2 behaviour).
   */
  async createOrder(orderData, items = []) {
    if (!Array.isArray(items) || items.length === 0) {
      throw new Error('At least one line item (SKU) is required');
    }

    // Every order_item MUST land in exactly one first gate (pre_approvals or
    // order_approvals) - there is no third path. Guarding this here (not just
    // in the route validator) means createOrder can never silently mint a
    // gate-less, permanently-orphaned order_item even if some future caller
    // reaches this service directly, bypassing HTTP validation.
    const orderTypeNorm = (orderData.orderType || '').toLowerCase().trim();
    const isPreApproval = orderTypeNorm === 'pre-approval';
    const isRegular = orderTypeNorm === 'regular';
    if (!isPreApproval && !isRegular) {
      throw new Error(`orderType must be 'regular' or 'pre-approval', got: ${JSON.stringify(orderData.orderType)}`);
    }

    return dbV2.transaction(async (tx) => {

      const orderNo = await generateOrderNo(tx, orderData.startDate);

      const [order] = await tx
        .insert(schema.orders)
        .values({
          orderNo,
          customerId: orderData.customerId ?? null,
          depotId: orderData.depotId ?? null,
          brokerId: orderData.brokerId ?? null,
          salespersonId: orderData.salespersonId ?? null,
          orderType: orderData.orderType ?? null,
          orderCategory: orderData.orderCategory ?? null,
          deliveryPurpose: orderData.deliveryPurpose ?? null,
          orderThrough: orderData.orderThrough ?? null,
          customerType: orderData.customerType ?? null,
          partySoDate: orderData.partySoDate ?? null,
          startDate: orderData.startDate ?? null,
          endDate: orderData.endDate ?? null,
          deliveryDate: orderData.deliveryDate ?? null,
          futurePeriodDate: orderData.futurePeriodDate ?? null,
          customerContactPersonName: orderData.customerContactPersonName ?? null,
          customerContactPersonWhatsappNo: orderData.customerContactPersonWhatsappNo ?? null,
          customerAddress: orderData.customerAddress ?? null,
          customerDeliveryAddress: orderData.customerDeliveryAddress ?? null,
          paymentTerms: orderData.paymentTerms ?? null,
          advancePaymentToBeTaken: orderData.advancePaymentToBeTaken ?? false,
          advanceAmount: orderData.advanceAmount ?? null,
          typeOfTransporting: orderData.typeOfTransporting ?? null,
          freightRate: orderData.freightRate ?? '0',
          gst: orderData.gst ?? null,
          manualSaudaNo: orderData.manualSaudaNo ?? orderData.processId ?? null,
          uploadSo: orderData.uploadSo ?? null,
          uploadCopy: orderData.uploadCopy ?? null,
          orderPunchRemarks: orderData.orderPunchRemarks ?? null,
          orderPunchUserId: orderData.userId ?? null,
        })
        .returning();

      const insertedItems = [];
      for (const item of items) {
        const [orderItem] = await tx
          .insert(schema.orderItems)
          .values({
            orderId: order.id,
            skuId: item.skuId ?? null,
            uom: item.uom ?? null,
            alternateUom: item.alternateUom ?? null,
            alternateQtyKg: item.alternateQtyKg ?? null,
            oilType: item.oilType ?? null,
            orderQuantity: item.orderQuantity ?? null,
            // Frozen WRITE-ONCE at punch: the auditable original and the hard ceiling
            // this product line can never exceed (see qty_guard trigger). A punch row
            // is its own budget-family root, so budget_root_id stays NULL.
            originalOrderQuantity: item.orderQuantity ?? null,
            // Regular orders skip Pre-Approval, so remaining_qty is knowable
            // immediately; pre-approval orders leave it null until that gate
            // sets the approved qty.
            remainingQty: isRegular ? item.orderQuantity ?? null : null,
            rateOfMaterial: item.rateOfMaterial ?? null,
            ratePer15kg: item.ratePer15kg ?? null,
            ratePerLtr: item.ratePerLtr ?? null,
            origin: 'punch',
          })
          .returning();

        if (isPreApproval) {
          const plannedAt = await getPlannedAt(tx, 'Pre Approval');
          await tx.insert(schema.preApprovals).values({ orderItemId: orderItem.id, plannedAt });
        } else if (isRegular) {
          const plannedAt = await getPlannedAt(tx, 'Approval of Order');
          await tx.insert(schema.orderApprovals).values({ orderItemId: orderItem.id, plannedAt });
        }

        insertedItems.push(orderItem);
      }

      Logger.info(`Order created: ${order.orderNo} with ${insertedItems.length} item(s)`);
      return {
        success: true,
        message: 'Order created successfully',
        data: { order, items: insertedItems },
      };
    });
  }

  /**
   * Get all orders with pagination (v2). Returns one row per real order
   * (base DO) with its customer/depot names and nested line items.
   * @param {Object} filters - { order_no, customer_name, order_type }
   * @param {Object} pagination - { page, limit }
   * @returns {Promise<Object>} Orders list
   */
  async getAllOrders(filters = {}, pagination = {}) {
    try {
      const page = parseInt(pagination.page) || 1;
      const limit = parseInt(pagination.limit) || 10;
      const offset = (page - 1) * limit;

      const conditions = [];
      if (filters.order_no) {
        conditions.push(sql`${schema.orders.orderNo} ILIKE ${'%' + filters.order_no + '%'}`);
      }
      if (filters.customer_name) {
        conditions.push(sql`${schema.customers.customerName} ILIKE ${'%' + filters.customer_name + '%'}`);
      }
      if (filters.order_type) {
        // orderType is an enum column; compare as text so an unknown value is a
        // clean no-match instead of an invalid-enum-cast error.
        conditions.push(sql`${schema.orders.orderType}::text = ${filters.order_type}`);
      }
      const where = conditions.length ? and(...conditions) : undefined;

      const [{ count }] = await dbV2
        .select({ count: sql`count(*)::int` })
        .from(schema.orders)
        .leftJoin(schema.customers, eq(schema.customers.id, schema.orders.customerId))
        .where(where);

      const rows = await dbV2
        .select({ order: schema.orders, customerName: schema.customers.customerName, depotName: schema.depots.depotName })
        .from(schema.orders)
        .leftJoin(schema.customers, eq(schema.customers.id, schema.orders.customerId))
        .leftJoin(schema.depots, eq(schema.depots.id, schema.orders.depotId))
        .where(where)
        .orderBy(desc(schema.orders.createdAt), asc(schema.orders.orderNo))
        .limit(limit)
        .offset(offset);

      const orderIds = rows.map((r) => r.order.id);
      const itemsByOrder = {};
      if (orderIds.length) {
        const items = await dbV2.select().from(schema.orderItems).where(inArray(schema.orderItems.orderId, orderIds));
        for (const it of items) {
          (itemsByOrder[it.orderId] = itemsByOrder[it.orderId] || []).push(it);
        }
      }

      const data = rows.map((r) => ({
        ...r.order,
        customer_name: r.customerName,
        depo_name: r.depotName,
        items: itemsByOrder[r.order.id] || [],
      }));

      return {
        success: true,
        data,
        pagination: { page, limit, total: count, totalPages: Math.ceil(count / limit) },
      };
    } catch (error) {
      Logger.error('Error fetching orders', error);
      throw new Error('Failed to fetch orders');
    }
  }

  /**
   * Get order by order number (v2) with its line items.
   * @param {string} orderNo - Order number (base DO)
   * @returns {Promise<Object>} Order details (data is an array, as before)
   */
  async getOrderByNumber(orderNo) {
    try {
      const [row] = await dbV2
        .select({ order: schema.orders, customerName: schema.customers.customerName, depotName: schema.depots.depotName })
        .from(schema.orders)
        .leftJoin(schema.customers, eq(schema.customers.id, schema.orders.customerId))
        .leftJoin(schema.depots, eq(schema.depots.id, schema.orders.depotId))
        .where(eq(schema.orders.orderNo, orderNo));

      if (!row) {
        throw new Error('Order not found');
      }

      const items = await dbV2.select().from(schema.orderItems).where(eq(schema.orderItems.orderId, row.order.id));

      return {
        success: true,
        data: [{ ...row.order, customer_name: row.customerName, depo_name: row.depotName, items }],
      };
    } catch (error) {
      Logger.error('Error fetching order', error);
      throw error;
    }
  }

  /**
   * Update an order's header fields (v2). Only order-level columns are
   * updatable here (per-line SKU/qty/rate edits go through the stage services).
   * Accepts snake_case (old API) or camelCase keys.
   * @param {number} id - orders.id (serial PK)
   * @param {Object} updateData
   * @returns {Promise<Object>} Updated order
   */
  async updateOrder(id, updateData = {}) {
    try {
      const orderId = parseInt(id, 10);
      if (isNaN(orderId)) throw new Error('Invalid order id');

      const setObj = {};
      for (const [key, value] of Object.entries(updateData)) {
        const camel = toCamelCase(key);
        if (UPDATABLE_ORDER_FIELDS.has(camel)) setObj[camel] = value;
      }
      if (Object.keys(setObj).length === 0) {
        throw new Error('No updatable order fields provided');
      }

      const [updated] = await dbV2
        .update(schema.orders)
        .set(setObj)
        .where(eq(schema.orders.id, orderId))
        .returning();

      if (!updated) {
        throw new Error('Order not found');
      }

      return { success: true, message: 'Order updated successfully', data: updated };
    } catch (error) {
      Logger.error('Error updating order', error);
      throw error;
    }
  }

  /**
   * Delete an order (v2). Only orders that have NOT yet produced any dispatch
   * shipment can be hard-deleted (a freshly-punched mistake); anything with a
   * shipment must be reverted through the stages first, and commitment-raised
   * orders must be adjusted via the commitment instead. Cascades the order's
   * items and their pre-dispatch gate rows in one transaction.
   * @param {number} id - orders.id (serial PK)
   * @returns {Promise<Object>} Delete confirmation
   */
  async deleteOrder(id) {
    const orderId = parseInt(id, 10);
    if (isNaN(orderId)) throw new Error('Invalid order id');

    return dbV2.transaction(async (tx) => {
      const [order] = await tx.select({ id: schema.orders.id }).from(schema.orders).where(eq(schema.orders.id, orderId));
      if (!order) throw new Error('Order not found');

      const items = await tx.select({ id: schema.orderItems.id }).from(schema.orderItems).where(eq(schema.orderItems.orderId, orderId));
      const itemIds = items.map((i) => i.id);

      if (itemIds.length) {
        const shipments = await tx.select({ id: schema.dispatches.id }).from(schema.dispatches).where(inArray(schema.dispatches.orderItemId, itemIds));
        if (shipments.length > 0) {
          throw new Error('Cannot delete an order that already has dispatched shipments — revert those first');
        }

        // Check BOTH commitment_details FKs (order_id and order_item_id): a
        // commitment raise sets both to the spawned order/line, so either one
        // matching means this order came from a commitment. Guarding both keeps
        // the friendly message airtight instead of ever letting a raw FK error
        // through, even if a future change links them differently.
        const commitLinks = await tx.select({ id: schema.commitmentDetails.id }).from(schema.commitmentDetails)
          .where(or(
            eq(schema.commitmentDetails.orderId, orderId),
            inArray(schema.commitmentDetails.orderItemId, itemIds),
          ));
        if (commitLinks.length > 0) {
          throw new Error('Cannot delete an order raised from a commitment — adjust the commitment instead');
        }

        // No shipments exist (guarded above), so only the pre-dispatch gate
        // rows can be present. Delete them, then the items (a single DELETE
        // over order_items also resolves the intra-order split_from_item_id
        // self-FK, since referencing + referenced rows go in the same statement).
        await tx.delete(schema.dispatchPlannings).where(inArray(schema.dispatchPlannings.orderItemId, itemIds));
        await tx.delete(schema.orderApprovals).where(inArray(schema.orderApprovals.orderItemId, itemIds));
        await tx.delete(schema.preApprovals).where(inArray(schema.preApprovals.orderItemId, itemIds));
        await tx.delete(schema.orderItems).where(eq(schema.orderItems.orderId, orderId));
      }

      await tx.delete(schema.orders).where(eq(schema.orders.id, orderId));

      return { success: true, message: 'Order deleted successfully' };
    });
  }

  /**
   * Get pending pre-approval orders
   * Pending: planned_1 IS NOT NULL AND actual_1 IS NULL
   * @param {Object} filters - Filter parameters
   * @param {Object} pagination - Pagination parameters
   * @returns {Promise<Object>} Pending orders
   */
  // Pre-Approval pending list (gate 1): order_items whose pre_approvals gate is
  // still open. In v2 there are no order_no-suffix split rows to exclude - a
  // partial-approval leftover is just another order_items row with its own open
  // pre_approvals gate, so it belongs in the list on its own merits.
  async getPendingPreApprovals(filters = {}, pagination = {}) {
    return this._listPreApproval({ ...filters, ...pagination, open: true });
  }

  // Pre-Approval history: order_items whose pre_approvals gate is closed.
  async getPreApprovalHistory(filters = {}, pagination = {}) {
    return this._listPreApproval({ ...filters, ...pagination, open: false });
  }

  async _listPreApproval({ open, page = 1, limit = 25, order_no, customer_name, start_date, end_date }) {
    page = parseInt(page) || 1;
    limit = parseInt(limit) || 25;

    const conditions = [
      isNotNull(schema.preApprovals.plannedAt),
      open ? isNull(schema.preApprovals.actualAt) : isNotNull(schema.preApprovals.actualAt),
    ];
    if (order_no) {
      conditions.push(sql`(${schema.orders.orderNo} ILIKE ${'%' + order_no + '%'} OR ${schema.customers.customerName} ILIKE ${'%' + order_no + '%'})`);
    } else if (customer_name) {
      conditions.push(sql`${schema.customers.customerName} ILIKE ${'%' + customer_name + '%'}`);
    }
    if (start_date && end_date) {
      conditions.push(sql`${schema.orders.deliveryDate} BETWEEN ${start_date} AND ${end_date}`);
    }
    const where = and(...conditions);

    // Pending rows are paginated by DISTINCT ORDER (not by raw order_item row):
    // a page always corresponds to N whole orders, so an order's line items —
    // which the frontend groups back into one visual row per order — can never
    // be split across two pages. History keeps the original row-level count/
    // pagination (ordered by actual_at, not an order-level column, so grouping
    // pagination doesn't apply there).
    let count;
    let pageOrderIds = null;
    if (open) {
      const [{ distinctCount }] = await dbV2
        .select({ distinctCount: sql`count(distinct ${schema.orders.id})::int` })
        .from(schema.preApprovals)
        .innerJoin(schema.orderItems, eq(schema.orderItems.id, schema.preApprovals.orderItemId))
        .innerJoin(schema.orders, eq(schema.orders.id, schema.orderItems.orderId))
        .leftJoin(schema.customers, eq(schema.customers.id, schema.orders.customerId))
        .where(where);
      count = distinctCount;

      const pageOrders = await dbV2
        .selectDistinct({ id: schema.orders.id, partySoDate: schema.orders.partySoDate, orderNo: schema.orders.orderNo })
        .from(schema.preApprovals)
        .innerJoin(schema.orderItems, eq(schema.orderItems.id, schema.preApprovals.orderItemId))
        .innerJoin(schema.orders, eq(schema.orders.id, schema.orderItems.orderId))
        .leftJoin(schema.customers, eq(schema.customers.id, schema.orders.customerId))
        .where(where)
        .orderBy(sql`${schema.orders.partySoDate} DESC, ${schema.orders.orderNo} DESC`)
        .limit(limit)
        .offset((page - 1) * limit);
      pageOrderIds = pageOrders.map((o) => o.id);

      if (pageOrderIds.length === 0) {
        return {
          success: true,
          data: [],
          pagination: { page, limit, total: count, totalPages: Math.ceil(count / limit) },
        };
      }
    } else {
      const [{ count: rowCount }] = await dbV2
        .select({ count: sql`count(*)::int` })
        .from(schema.preApprovals)
        .innerJoin(schema.orderItems, eq(schema.orderItems.id, schema.preApprovals.orderItemId))
        .innerJoin(schema.orders, eq(schema.orders.id, schema.orderItems.orderId))
        .leftJoin(schema.customers, eq(schema.customers.id, schema.orders.customerId))
        .where(where);
      count = rowCount;
    }

    const punchUser = alias(schema.users, 'punch_user');
    const preApprovalUser = alias(schema.users, 'pre_approval_doer');

    let rowsQuery = dbV2
      .select({
        preApprovalId: schema.preApprovals.id,
        plannedAt: schema.preApprovals.plannedAt,
        actualAt: schema.preApprovals.actualAt,
        orderItem: schema.orderItems,
        order: schema.orders,
        customer: schema.customers,
        depot: schema.depots,
        sku: schema.skus,
        orderPunchUser: punchUser.username,
        preApprovalUser: preApprovalUser.username,
      })
      .from(schema.preApprovals)
      .innerJoin(schema.orderItems, eq(schema.orderItems.id, schema.preApprovals.orderItemId))
      .innerJoin(schema.orders, eq(schema.orders.id, schema.orderItems.orderId))
      .leftJoin(schema.customers, eq(schema.customers.id, schema.orders.customerId))
      .leftJoin(schema.depots, eq(schema.depots.id, schema.orders.depotId))
      .leftJoin(schema.skus, eq(schema.skus.id, schema.orderItems.skuId))
      .leftJoin(punchUser, eq(punchUser.id, schema.orders.orderPunchUserId))
      .leftJoin(preApprovalUser, eq(preApprovalUser.id, schema.preApprovals.approvedByUserId))
      .where(open ? and(where, inArray(schema.orders.id, pageOrderIds)) : where)
      // Newest first: sort pending rows by DO Date (party_so_date), tie-broken
      // by order_no so same-day orders stay in a stable, deterministic order.
      .orderBy(open ? sql`${schema.orders.partySoDate} DESC, ${schema.orders.orderNo} DESC` : desc(schema.preApprovals.actualAt));

    if (!open) {
      rowsQuery = rowsQuery.limit(limit).offset((page - 1) * limit);
    }

    const rows = await rowsQuery;

    return {
      success: true,
      data: rows,
      pagination: { page, limit, total: count, totalPages: Math.ceil(count / limit) },
    };
  }

  /**
   * Submit Pre-Approval (gate 1) for one order_item.
   *
   * Closes the item's pre_approvals gate, queues the next gate (order_approvals),
   * and - for a partial Sales approval - splits the leftover qty into a NEW
   * order_item carrying the PRE-change SKU, queued back into Pre-Approval fresh.
   *
   * The leftover being a distinct order_items row (its own immutable id) is what
   * makes v2 immune to the old cascade bug: changing the approved row's skuId can
   * never orphan the leftover or any sibling dispatch, because nothing is matched
   * by order_no/product_name text anymore.
   *
   * @param {number} orderItemId
   * @param {Object} data - { approvalQty, skuId?, rate?, ratePer15kg?, ratePerLtr?, userId? }
   */
  async submitPreApproval(orderItemId, data = {}) {
    return dbV2.transaction((tx) => this._submitPreApprovalTx(tx, orderItemId, data));
  }

  // Shared by submitPreApproval (own transaction) and submitBatch (composes
  // several of these inside ONE transaction so a mid-batch failure rolls
  // everything back together).
  async _submitPreApprovalTx(tx, orderItemId, data = {}) {
      const [current] = await tx
        .select({ item: schema.orderItems, order: schema.orders })
        .from(schema.orderItems)
        .innerJoin(schema.orders, eq(schema.orders.id, schema.orderItems.orderId))
        .where(eq(schema.orderItems.id, orderItemId));

      if (!current) throw new Error('Order item not found');

      // Fail loudly with a specific, actionable message instead of letting a raw
      // FK-constraint violation reach the client as an opaque 500.
      if (data.skuId != null) {
        const [skuExists] = await tx.select({ id: schema.skus.id }).from(schema.skus).where(eq(schema.skus.id, data.skuId));
        if (!skuExists) throw new Error(`SKU id ${data.skuId} not found — cannot update order_item ${orderItemId}`);
      }

      // Backstop: never change the product of a line that already has shipments — it
      // would relabel already-dispatched trucks (the reported v1/v2 bug). The revert
      // now splits the un-dispatched remainder into a fresh (ship-free) line, so a line
      // reaching Pre-Approval normally has no shipments; this only fires if reached
      // another way. Change the SKU on the split remainder, not on the shipped line.
      if (data.skuId != null && data.skuId !== current.item.skuId) {
        const [hasShipment] = await tx
          .select({ id: schema.dispatches.id })
          .from(schema.dispatches)
          .where(eq(schema.dispatches.orderItemId, orderItemId))
          .limit(1);
        if (hasShipment) {
          throw new Error('Cannot change the product of a line that already has dispatched shipments. Revert it (which splits off the un-dispatched remainder) and change the new line instead.');
        }
      }

      const isStockTransferOrder = isStockTransfer(current.order.orderCategory);
      const approvalQty = parseFloat(data.approvalQty) || 0;

      // Prefer remainingQty (source of truth after any prior revert-to-pre-approval
      // from a later stage) over orderQuantity, which can be stale then - mirrors
      // the reference implementation's logic exactly.
      const orderQty = current.item.remainingQty != null
        ? parseFloat(current.item.remainingQty) || 0
        : parseFloat(current.item.orderQuantity) || 0;

      // Sales can only ever approve DOWN from what's available - approving above it
      // would push the product line's total past its original punch qty. Surface a
      // clean, user-facing error here; the qty_guard DB trigger is the hard backstop
      // that catches any path that slips past this. Stock Transfer is exempt (approves
      // above remaining by design).
      if (!isStockTransferOrder && approvalQty > orderQty + 0.0001) {
        throw new Error(`Approved qty (${approvalQty}) cannot exceed the available quantity (${orderQty}) for this line`);
      }

      // Stock Transfer may approve above remaining (no cap); Sales can only shrink.
      const effectiveOrderQty = isStockTransferOrder && approvalQty > orderQty ? approvalQty : orderQty;
      // Stock Transfer never splits; Sales splits when the approved chunk is smaller.
      const isPartial = !isStockTransferOrder && approvalQty > 0 && approvalQty < effectiveOrderQty;
      const approvedRowQty = isPartial ? approvalQty : effectiveOrderQty;
      const remainingQty = approvalQty > 0 ? approvalQty : effectiveOrderQty;

      // Stale-write guard: only close a pre_approvals row still open. A legit
      // pending row always satisfies this, so it's a no-op on the happy path and
      // fires ONLY on a stale/duplicate submit (already approved/reverted/moved).
      const closedGate = await tx
        .update(schema.preApprovals)
        .set({ actualAt: new Date(), approvedByUserId: data.userId ?? null })
        .where(and(
          eq(schema.preApprovals.orderItemId, orderItemId),
          isNotNull(schema.preApprovals.plannedAt),
          isNull(schema.preApprovals.actualAt),
        ))
        .returning();
      assertStageOpen({ rowCount: closedGate.length }, 'Pre-Approval');

      const [approved] = await tx
        .update(schema.orderItems)
        .set({
          skuId: data.skuId ?? current.item.skuId,
          orderQuantity: approvedRowQty,
          approvedQty: approvalQty > 0 ? approvalQty : effectiveOrderQty,
          remainingQty: remainingQty,
          // The reference sets rate_of_material and final_rate to the SAME entered
          // value at this gate (there is no separate SKU-rate input).
          rateOfMaterial: data.rate != null ? data.rate : current.item.rateOfMaterial,
          finalRate: data.rate != null ? data.rate : current.item.finalRate,
          ratePer15kg: data.ratePer15kg != null ? data.ratePer15kg : current.item.ratePer15kg,
          ratePerLtr: data.ratePerLtr != null ? data.ratePerLtr : current.item.ratePerLtr,
        })
        .where(eq(schema.orderItems.id, orderItemId))
        .returning();

      // Queue the next gate (Order Approval).
      const nextPlannedAt = await getPlannedAt(tx, 'Approval of Order');
      await tx.insert(schema.orderApprovals).values({ orderItemId, plannedAt: nextPlannedAt });

      // Partial Sales approval: split leftover into its own order_item (carrying
      // the pre-change SKU) and re-queue it into Pre-Approval.
      let split = null;
      if (isPartial) {
        const leftoverQty = effectiveOrderQty - approvalQty;
        const [newItem] = await tx
          .insert(schema.orderItems)
          .values({
            orderId: current.item.orderId,
            skuId: current.item.skuId,
            uom: current.item.uom,
            alternateUom: current.item.alternateUom,
            alternateQtyKg: current.item.alternateQtyKg,
            oilType: current.item.oilType,
            orderQuantity: leftoverQty,
            // A split is a slice of the SAME punched budget - it does NOT get its own
            // original (that lives once on the root, so SUM(original) across a family
            // still equals the punch). It just points at the family root; the qty guard
            // caps the family's total order_quantity at the root's original.
            budgetRootId: current.item.budgetRootId ?? current.item.id,
            rateOfMaterial: current.item.rateOfMaterial,
            ratePer15kg: current.item.ratePer15kg,
            ratePerLtr: current.item.ratePerLtr,
            origin: 'split',
            splitFromItemId: orderItemId,
          })
          .returning();
        const splitPlannedAt = await getPlannedAt(tx, 'Pre Approval');
        await tx.insert(schema.preApprovals).values({ orderItemId: newItem.id, plannedAt: splitPlannedAt });
        split = newItem;
        Logger.info(`Partial pre-approval: leftover ${leftoverQty} -> new order_item ${newItem.id}`);
      }

      Logger.info(`Pre-approval submitted for order_item ${orderItemId}`);
      return {
        success: true,
        message: split
          ? `Pre-approval submitted. Remaining quantity (${split.orderQuantity}) added to pending.`
          : 'Pre-approval submitted successfully',
        data: { approved, remaining: split },
      };
  }

  /**
   * Get all suffixes used for a given order number prefix
   * @param {string} prefix - The base order number prefix (e.g., DO-668)
   * @returns {Promise<Array>} List of suffix characters
   */
  async getOrderSuffixes(prefix) {
    try {
      // In v2 there is exactly one `orders` row per real order — the old
      // letter-suffix variants (0084A/0084B) no longer exist. Scanning v2 for
      // a trailing letter therefore returns [] for a normal DO prefix, which
      // is the CORRECT answer (no suffix is occupied): the pre-approval page's
      // add-product-row helper then starts fresh at 'A'. Kept as a real query
      // (not a hardcoded []) so any legacy lettered order_no still round-trips.
      const rows = await dbV2
        .select({ orderNo: schema.orders.orderNo })
        .from(schema.orders)
        .where(sql`${schema.orders.orderNo} LIKE ${prefix + '%'}`);

      const suffixes = rows.map((row) => {
        const orderNo = row.orderNo || "";
        if (orderNo.startsWith(prefix)) {
          const suffixPart = orderNo.substring(prefix.length);
          const match = suffixPart.match(/([A-Z])/i);
          return match ? match[1].toUpperCase() : null;
        }
        return null;
      }).filter(Boolean);

      return Array.from(new Set(suffixes));
    } catch (error) {
      Logger.error(`Error fetching suffixes for prefix ${prefix}`, error);
      throw error;
    }
  }

  /**
   * Deduct qty from an existing PENDING pre-approval order_item without
   * advancing it in the workflow. Used when a new SKU (or an over-budget
   * approval) consumes budget from sibling order_items still open at
   * Pre-Approval. Mirrors the reference exactly, on v2's order_items/
   * pre_approvals tables instead of the old mega-row: remainingQty is NULL
   * pre-approval (only Regular orders seed it at Order Punch), so it's left
   * NULL here too unless it was already non-null; qty===0 additionally CLOSES
   * the pre_approvals gate (actualAt=now) so the row exits pending as a
   * zero-qty audit-only record instead of advancing.
   *
   * approved_qty is reconciled the same way remaining_qty is: when a line's
   * budget is drawn down we CAP approved_qty at the new order_quantity (never
   * raise it, never fabricate one where it was NULL). Without this, a sibling
   * drained to fund a new SKU / over-approval kept its stale approved_qty (e.g.
   * order_quantity 0 but approved_qty 50, or 49/51) - which mis-displays in the
   * pre-approval modal (it pre-fills from approved_qty) AND then trips the
   * "approved qty cannot exceed available" guard on the next submit. Only ever
   * a decrease, so it's always <= the frozen original and the qty_guard trigger
   * can't reject it.
   * @param {object} tx - drizzle transaction (required - always called inside one)
   */
  async _deductBudgetTx(tx, orderItemId, orderQuantity) {
    const qty = Math.max(0, parseFloat(orderQuantity) || 0);

    const [current] = await tx
      .select({ remainingQty: schema.orderItems.remainingQty, approvedQty: schema.orderItems.approvedQty })
      .from(schema.orderItems)
      .where(eq(schema.orderItems.id, orderItemId));
    if (!current) throw new Error('Order item not found');

    const hadRemaining = current.remainingQty != null;
    const newRemaining = qty === 0
      ? (hadRemaining ? 0 : null)
      : (hadRemaining ? Math.min(parseFloat(current.remainingQty) || 0, qty) : null);

    // Cap approved_qty at the new order_quantity (leave NULL as NULL). qty===0
    // (sibling fully exhausted) drives it to 0; a partial draw caps it to what's
    // left. Never increases it.
    const hadApproved = current.approvedQty != null;
    const newApproved = hadApproved
      ? Math.min(parseFloat(current.approvedQty) || 0, qty)
      : null;

    const [updated] = await tx
      .update(schema.orderItems)
      .set({ orderQuantity: qty, remainingQty: newRemaining, approvedQty: newApproved })
      .where(eq(schema.orderItems.id, orderItemId))
      .returning();

    if (qty === 0) {
      await tx
        .update(schema.preApprovals)
        .set({ actualAt: new Date() })
        .where(and(
          eq(schema.preApprovals.orderItemId, orderItemId),
          isNotNull(schema.preApprovals.plannedAt),
          isNull(schema.preApprovals.actualAt),
        ));
    }

    return updated;
  }

  // Public single-row endpoint (PATCH /deduct-budget/:id) - wraps the shared
  // tx-scoped implementation in its own transaction.
  async deductBudget(orderItemId, orderQuantity) {
    return dbV2.transaction((tx) => this._deductBudgetTx(tx, orderItemId, orderQuantity));
  }

  /**
   * Atomically submit one or more pre-approvals, create any new SKU lines, and
   * apply cascade deductions in a single DB transaction so totals never go out
   * of sync on partial failure (a new item that fails to get funded, or a
   * cascade deduction that fails, rolls back everything - no orphan rows).
   * @param {Array<{id: number, data: object}>} approvals
   * @param {Array<{base_do: string, oil_type: string, qty: number}>} cascadeBudgets -
   *   distributed AFTER all approvals/splits/new items are created, so it can target them too.
   * @param {Array<{id: number, orderQuantity: number}>} deductions - legacy explicit deductions
   * @param {Array<number>} skipIds - Stock Transfer order_items to auto-close (zero qty, no dispatch)
   * @param {Array<{orderId: number, skuId: number, uom, oilType, orderQuantity, rateOfMaterial, ratePerLtr, ratePer15kg}>} newItems -
   *   a SKU not originally on the order, added during batch-approve. Inserted onto the EXISTING
   *   order (v2 already supports multiple line items per order - no new orders row, no letter-suffix
   *   hack). Skips Pre-Approval entirely and lands straight in Order Approval, exactly like a
   *   "Regular" order_item at Order Punch (remainingQty seeded immediately, no pre_approvals row).
   *   Its own qty is never reduced - cascadeBudgets is what funds it, by deducting from siblings.
   */
  async submitBatch(approvals = [], cascadeBudgets = [], deductions = [], skipIds = [], newItems = []) {
    return dbV2.transaction(async (tx) => {
      const approvedIds = [];
      const results = [];
      for (const { id, data } of approvals) {
        const result = await this._submitPreApprovalTx(tx, id, data);
        results.push(result);
        approvedIds.push(parseInt(id, 10));
      }

      const newItemResults = [];
      for (const item of newItems) {
        const orderId = parseInt(item.orderId, 10);
        const skuId = parseInt(item.skuId, 10);
        if (!orderId) throw new Error('New SKU line is missing its order');
        if (!skuId) throw new Error('New SKU line could not be matched to a known SKU');

        const [orderExists] = await tx.select({ id: schema.orders.id }).from(schema.orders).where(eq(schema.orders.id, orderId));
        if (!orderExists) throw new Error(`Order ${orderId} not found`);

        const qty = parseFloat(item.orderQuantity) || 0;
        const [newItem] = await tx
          .insert(schema.orderItems)
          .values({
            orderId,
            skuId,
            uom: item.uom ?? null,
            oilType: item.oilType ?? null,
            orderQuantity: qty,
            // A newly-added SKU was never on the original order; its funded qty IS
            // its original, and it's its own budget-family root (funded by deducting
            // from siblings, not by splitting one line). budget_root_id stays NULL.
            originalOrderQuantity: qty,
            remainingQty: qty,
            rateOfMaterial: item.rateOfMaterial ?? null,
            finalRate: item.rateOfMaterial ?? null,
            ratePerLtr: item.ratePerLtr ?? null,
            ratePer15kg: item.ratePer15kg ?? null,
            origin: 'added',
          })
          .returning();

        const plannedAt = await getPlannedAt(tx, 'Approval of Order');
        await tx.insert(schema.orderApprovals).values({ orderItemId: newItem.id, plannedAt });

        approvedIds.push(newItem.id); // defensive: never a cascade-donation target (no pre_approvals row anyway)
        newItemResults.push(newItem);
        Logger.info(`New SKU line ${newItem.id} added to order ${orderId}, straight to Order Approval`);
      }

      // Legacy explicit deductions (kept for backward compat; not currently sent by the frontend)
      for (const { id, orderQuantity } of deductions) {
        await this._deductBudgetTx(tx, id, orderQuantity);
      }

      // Server-side cascade: frontend sends {base_do, oil_type, qty} tuples (base_do
      // = orders.orderNo, exact match - v2 has no letter-suffix variants to fuzzy-match).
      // Targets sibling order_items on the SAME order sharing oil_type, still open at
      // Pre-Approval, excluding rows just approved above.
      for (const { base_do, oil_type, qty } of cascadeBudgets) {
        const need = parseFloat(qty) || 0;
        if (need <= 0) continue;

        const conditions = [
          eq(schema.orders.orderNo, base_do),
          sql`LOWER(TRIM(COALESCE(${schema.orderItems.oilType}, ''))) = LOWER(TRIM(${oil_type}))`,
          isNotNull(schema.preApprovals.plannedAt),
          isNull(schema.preApprovals.actualAt),
        ];
        if (approvedIds.length > 0) conditions.push(notInArray(schema.orderItems.id, approvedIds));

        const targets = await tx
          .select({ id: schema.orderItems.id, orderQuantity: schema.orderItems.orderQuantity })
          .from(schema.orderItems)
          .innerJoin(schema.orders, eq(schema.orders.id, schema.orderItems.orderId))
          .innerJoin(schema.preApprovals, eq(schema.preApprovals.orderItemId, schema.orderItems.id))
          .where(and(...conditions))
          .orderBy(asc(schema.orderItems.id));

        let remaining = need;
        for (const target of targets) {
          if (remaining <= 0) break;
          const targetQty = parseFloat(target.orderQuantity) || 0;
          if (targetQty <= 0) continue;
          const deduction = Math.min(targetQty, remaining);
          remaining -= deduction;
          await this._deductBudgetTx(tx, target.id, Math.max(0, targetQty - deduction));
        }

        if (remaining > 0) {
          Logger.warn(`[CASCADE] Unabsorbed budget: ${remaining} of ${oil_type} for ${base_do}`);
        }
      }

      // Auto-close skipped Stock Transfer order_items still pending at Pre-Approval:
      // zero the qty and close the gate so they exit the pending list without a dispatch.
      if (skipIds.length > 0) {
        const safeIds = skipIds.map(id => parseInt(id, 10)).filter(id => !isNaN(id));
        if (safeIds.length > 0) {
          const skippable = await tx
            .select({ id: schema.orderItems.id })
            .from(schema.orderItems)
            .innerJoin(schema.orders, eq(schema.orders.id, schema.orderItems.orderId))
            .innerJoin(schema.preApprovals, eq(schema.preApprovals.orderItemId, schema.orderItems.id))
            .where(and(
              inArray(schema.orderItems.id, safeIds),
              sql`UPPER(TRIM(COALESCE(${schema.orders.orderCategory}::text, ''))) = 'STOCK TRANSFER'`,
              isNotNull(schema.preApprovals.plannedAt),
              isNull(schema.preApprovals.actualAt),
            ));
          for (const row of skippable) {
            await this._deductBudgetTx(tx, row.id, 0);
          }
          Logger.info(`[BATCH] Auto-closed ${skippable.length} skipped Stock Transfer row(s): ${skippable.map(r => r.id).join(', ')}`);
        }
      }

      return { success: true, results, newItems: newItemResults };
    });
  }
}

module.exports = new OrderDispatchService();
